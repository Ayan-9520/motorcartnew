function demoPreowned(partial: {
  id: string;
  brand: string;
  model: string;
  variant: string;
  price: number;
  year: number;
  kms: number;
  city: string;
  image: string;
  fuel?: string;
}): PreownedCarListing {
  const title = `${partial.brand} ${partial.model} ${partial.variant}`;
  return {
    id: partial.id,
    slug: partial.id,
    title,
    brand: partial.brand,
    model: partial.model,
    variant: partial.variant,
    year: partial.year,
    price: partial.price,
    originalPrice: Math.round(partial.price * 1.08),
    fuelType: partial.fuel ?? "Petrol",
    transmission: "Automatic",
    bodyType: "SUV",
    category: "used-cars",
    condition: "used",
    kmsDriven: partial.kms,
    owners: 1,
    city: partial.city,
    state: "India",
    location: partial.city,
    images: [partial.image],
    features: ["Certified", "Insurance valid", "Service history"],
    isCertified: true,
    isFeatured: true,
    status: "available",
    saleMode: "dealer_offer",
    dealerName: "Motorcart Certified",
    dealerVerified: true,
    createdAt: new Date().toISOString(),
    aiPriceScore: 88,
    metadata: {
      fairPriceLabel: "great-deal",
      trustBadges: ["certified", "inspected", "warranty"],
      warrantyIncluded: true,
      inspectionScore: 92,
      onRoadPrice: Math.round(partial.price * 1.05),
    },
  };
}

